import {spawnSync} from 'node:child_process';
import path from 'node:path';
import os from 'node:os';
import fs from 'node:fs';
const base=path.resolve('direct');
const fake=fs.mkdtempSync(path.join(os.tmpdir(),'micehole-v3-remote-'));
const app=path.join(fake,'AppData');
fs.mkdirSync(app);
const req=JSON.stringify({jsonrpc:'2.0',id:1,method:'tools/list',params:{}})+'\n';
const cmd=path.join(base,'micehole-remote.cmd');
const env={...process.env,LOCALAPPDATA:app,MOUSE_HOLE_WORKSPACE:path.join(fake,'workspace')};
const blocked=spawnSync('cmd.exe',['/d','/c',cmd],{input:req,encoding:'utf8',env,timeout:5000});
if(blocked.status===0)throw Error('Unapproved remote access not blocked');
const consent=path.join(app,'MiceHoleV3');fs.mkdirSync(consent);
fs.writeFileSync(path.join(consent,'remote-high-privilege.enabled'),'consent-v1');
fs.mkdirSync(env.MOUSE_HOLE_WORKSPACE);
const granted=spawnSync('cmd.exe',['/d','/c',cmd],{input:req,encoding:'utf8',env,timeout:7000});
const tools=JSON.parse(granted.stdout).result.tools.map(x=>x.name);
if(granted.status!==0 || tools.length!==15 || !tools.includes('mouse_hole_run') || !tools.includes('mouse_hole_gui'))throw Error('Remote tool advertisement failed');
console.log(JSON.stringify({pass:true,remote_without_consent:'blocked',remote_with_consent:'15 tools registered',credential_isolation:'NOT_PROVEN',shell_remote:true}));
